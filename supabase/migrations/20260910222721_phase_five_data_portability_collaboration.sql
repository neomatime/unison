create or replace function public.search_organization_records(
  target_organization uuid,
  search_query text,
  result_limit integer default 20
)
returns table (
  resource text,
  record_id uuid,
  title text,
  subtitle text,
  href text,
  updated_at timestamptz,
  rank real
)
language sql stable security invoker set search_path = ''
as $$
  with normalized as (
    select string_agg(quote_literal(term) || ':*', ' & ') as expression
    from regexp_split_to_table(lower(trim(search_query)), '[^[:alnum:]_-]+') as term
    where length(term) >= 2
  ), query as (
    select to_tsquery('simple', expression) as value
    from normalized
    where expression is not null
  )
  select
    records.resource,
    records.record_id,
    records.title,
    records.subtitle,
    records.href,
    records.updated_at,
    ts_rank(records.search_vector, query.value)::real as rank
  from public.record_index records
  cross join query
  where records.organization_id = target_organization
    and records.search_vector @@ query.value
  order by rank desc, records.updated_at desc
  limit least(greatest(coalesce(result_limit, 20), 1), 50);
$$;

revoke all on function public.search_organization_records(uuid, text, integer) from public, anon;
