create table public.documents (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  display_name text not null check (length(trim(display_name)) > 0),
  storage_bucket text not null default 'documents' check (storage_bucket = 'documents'),
  storage_path text not null,
  mime_type text not null,
  file_size bigint not null check (file_size > 0 and file_size <= 52428800),
  classification text not null default 'Project Evidence'
    check (classification in ('Project Evidence','Requirements','Compliance','Design Artefact','Commercial','Other')),
  confidentiality text not null default 'Internal'
    check (confidentiality in ('Internal','Confidential','Restricted')),
  linked_record_type text,
  linked_record_id uuid,
  linked_path text,
  description text,
  version integer not null default 1 check (version > 0),
  uploaded_by uuid default auth.uid() references auth.users(id) on delete set null,
  archived_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (organization_id, storage_path),
  unique (id, organization_id)
);

