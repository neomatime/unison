create or replace function private.index_platform_record_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  payload jsonb;
  target_org uuid;
  target_id uuid;
  target_title text;
  target_subtitle text;
  target_href text;
  should_remove boolean := false;
begin
  if auth.uid() is null and current_user not in ('postgres', 'service_role') then
    raise insufficient_privilege using message = 'An authenticated database role is required';
  end if;

  payload := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  target_org := (payload ->> 'organization_id')::uuid;
  target_id := (payload ->> 'id')::uuid;

  case tg_table_name
    when 'knowledge_articles' then
      target_title := payload ->> 'title';
      target_subtitle := concat_ws(' · ', payload ->> 'category', payload ->> 'status', payload ->> 'summary');
      target_href := '/knowledge/' || target_id;
      should_remove := payload ->> 'status' = 'archived' or payload ->> 'visibility' = 'internal';
    when 'integration_connections' then
      target_title := payload ->> 'name';
      target_subtitle := concat_ws(' · ', payload ->> 'provider', payload ->> 'status', payload ->> 'event_key');
      target_href := '/settings/integrations/' || target_id;
    when 'automation_rules' then
      target_title := payload ->> 'name';
      target_subtitle := concat_ws(' · ', payload ->> 'trigger_type', payload ->> 'status', payload ->> 'description');
      target_href := '/settings/automations/' || target_id;
    else
      raise exception 'Unsupported platform search resource: %', tg_table_name;
  end case;

  if tg_op = 'DELETE' or should_remove then
    delete from public.record_index
    where organization_id = target_org and resource = tg_table_name and record_id = target_id;
  else
    insert into public.record_index(organization_id, resource, record_id, title, subtitle, href, updated_at)
    values (
      target_org, tg_table_name, target_id,
      coalesce(target_title, 'Untitled record'), coalesce(target_subtitle, ''), target_href,
      coalesce((payload ->> 'updated_at')::timestamptz, (payload ->> 'created_at')::timestamptz, now())
    )
    on conflict (organization_id, resource, record_id) do update set
      title = excluded.title,
      subtitle = excluded.subtitle,
      href = excluded.href,
      updated_at = excluded.updated_at;
  end if;

  if exists (select 1 from public.organizations where id = target_org) then
    insert into public.record_change_events(organization_id, resource, record_id, operation, actor_id)
    values (target_org, tg_table_name, target_id, tg_op, auth.uid());
  end if;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

revoke all on function private.index_platform_record_change() from public, anon, authenticated, service_role;
create trigger knowledge_articles_search_realtime after insert or update or delete on public.knowledge_articles
  for each row execute function private.index_platform_record_change();
