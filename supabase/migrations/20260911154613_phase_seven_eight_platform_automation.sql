  returning id into target_run_id;

  insert into public.background_jobs(
    organization_id, rule_id, run_id, payload, idempotency_key
  ) values (
    target_rule.organization_id, target_rule.id, target_run_id,
    target_rule.action_config, 'manual:' || target_run_id
  );
  return target_run_id;
end;
$$;

