create or replace function private.record_subscription_event()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  event_action text;
begin
  if tg_op = 'INSERT' then
    event_action := 'created';
  elsif new.status = 'paused' and old.status <> 'paused' then
    event_action := 'paused';
  elsif new.status = 'active' and old.status = 'paused' then
    event_action := 'resumed';
  elsif new.status = 'cancelled' and old.status <> 'cancelled' then
    event_action := 'cancelled';
  else
    event_action := 'updated';
  end if;

  insert into public.subscription_events(
    organization_id, subscription_id, actor_id, action, old_value, new_value
  ) values (
    new.organization_id, new.id, auth.uid(), event_action,
    case when tg_op = 'UPDATE' then to_jsonb(old) else null end,
    to_jsonb(new)
  );
  return new;
end;
$$;

revoke all on function private.record_subscription_event() from public, anon, authenticated, service_role;
create trigger platform_subscriptions_history after insert or update on public.platform_subscriptions
  for each row execute function private.record_subscription_event();

create or replace function public.rotate_integration_secret(p_connection_id uuid)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_org uuid;
  generated_secret text;
begin
  select organization_id into target_org
  from public.integration_connections
  where id = p_connection_id;

  if target_org is null
     or not public.has_role(target_org, array['owner','admin']) then
    raise insufficient_privilege using message = 'Integration administration is required';
  end if;

  generated_secret := encode(extensions.gen_random_bytes(24), 'hex');
  insert into private.integration_secrets(connection_id, secret_hash, rotated_at)
  values (p_connection_id, extensions.digest(generated_secret, 'sha256'), now())
  on conflict (connection_id) do update
    set secret_hash = excluded.secret_hash, rotated_at = excluded.rotated_at;

  update public.integration_connections
  set secret_hint = right(generated_secret, 6), status = 'connected', last_error = null
  where id = p_connection_id;

  return generated_secret;
end;
$$;

