create or replace function public.ingest_integration_event(
  p_connection_id uuid,
  p_secret text,
  p_event_key text,
  p_external_id text default null,
  p_payload jsonb default '{}'::jsonb
)
returns table(event_id bigint, run_ids uuid[])
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_connection public.integration_connections%rowtype;
  target_event_id bigint;
  target_run_id uuid;
  collected_run_ids uuid[] := '{}';
  target_rule record;
begin
  if p_secret is null or length(p_secret) < 16 or length(p_secret) > 512
     or p_event_key is null or p_event_key !~ '^[a-z0-9][a-z0-9._-]{1,79}$'
     or jsonb_typeof(p_payload) <> 'object'
     or octet_length(p_payload::text) > 65536 then
    raise insufficient_privilege using message = 'Integration credential rejected';
  end if;

  select c.* into target_connection
  from public.integration_connections c
  join private.integration_secrets s on s.connection_id = c.id
  where c.id = p_connection_id
    and c.status = 'connected'
    and s.secret_hash = extensions.digest(p_secret, 'sha256');

  if target_connection.id is null
     or (target_connection.event_key <> '*' and target_connection.event_key <> p_event_key) then
    raise insufficient_privilege using message = 'Integration credential rejected';
  end if;

  insert into public.integration_events(
    organization_id, connection_id, event_key, external_id, payload
  ) values (
    target_connection.organization_id, target_connection.id, p_event_key,
    nullif(trim(p_external_id), ''), p_payload
  )
  on conflict (connection_id, external_id) where external_id is not null do nothing
  returning id into target_event_id;

  if target_event_id is null then
    select id into target_event_id
    from public.integration_events
    where connection_id = target_connection.id and external_id = p_external_id;
    return query select target_event_id, collected_run_ids;
    return;
  end if;

  update public.integration_connections
  set last_event_at = now(), last_error = null
  where id = target_connection.id;

  for target_rule in
    select r.id, r.organization_id, r.action_config
    from public.automation_rules r
    where r.organization_id = target_connection.organization_id
      and r.integration_connection_id = target_connection.id
      and r.trigger_type = 'integration_event'
      and r.status = 'active'
      and coalesce(r.trigger_config ->> 'event_key', '*') in ('*', p_event_key)
  loop
    insert into public.automation_runs(
      organization_id, rule_id, integration_event_id, trigger_type, input
    ) values (
      target_rule.organization_id, target_rule.id, target_event_id,
      'integration_event', p_payload
    ) returning id into target_run_id;

    insert into public.background_jobs(
      organization_id, rule_id, run_id, payload, idempotency_key
    ) values (
      target_rule.organization_id, target_rule.id, target_run_id,
      target_rule.action_config,
      'event:' || target_event_id || ':rule:' || target_rule.id
    );
    collected_run_ids := array_append(collected_run_ids, target_run_id);
  end loop;

  update public.integration_events
  set status = case when cardinality(collected_run_ids) > 0 then 'processed' else 'ignored' end
  where id = target_event_id;

  return query select target_event_id, collected_run_ids;
end;
$$;

revoke all on function public.ingest_integration_event(uuid,text,text,text,jsonb) from public;
grant execute on function public.ingest_integration_event(uuid,text,text,text,jsonb) to anon, authenticated, service_role;

create or replace function public.enqueue_automation_rule(
  p_rule_id uuid,
  p_input jsonb default '{}'::jsonb
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_rule public.automation_rules%rowtype;
  target_run_id uuid;
