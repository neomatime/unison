create or replace function private.enqueue_due_automation_schedules()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  target record;
  target_run_id uuid;
  queued_count integer := 0;
begin
  if not pg_try_advisory_xact_lock(hashtext('unison:enqueue-due-automation-schedules')) then
    return 0;
  end if;

  for target in
    select s.id as schedule_id, s.organization_id, s.rule_id,
      s.interval_minutes, s.next_run_at, r.action_config
    from public.automation_schedules s
    join public.automation_rules r
      on r.id = s.rule_id and r.organization_id = s.organization_id
    where s.enabled and s.next_run_at <= now() and r.status = 'active'
    order by s.next_run_at
    limit 100
    for update of s skip locked
  loop
    insert into public.automation_runs(organization_id, rule_id, trigger_type, input)
    values (
      target.organization_id, target.rule_id, 'schedule',
      jsonb_build_object('scheduled_for', target.next_run_at)
    ) returning id into target_run_id;

    insert into public.background_jobs(
      organization_id, rule_id, run_id, payload, idempotency_key
    ) values (
      target.organization_id, target.rule_id, target_run_id, target.action_config,
      'schedule:' || target.schedule_id || ':' || extract(epoch from target.next_run_at)::bigint
    ) on conflict (idempotency_key) do nothing;

    update public.automation_schedules
    set last_enqueued_at = now(),
        next_run_at = greatest(now(), target.next_run_at) + make_interval(mins => target.interval_minutes)
    where id = target.schedule_id;
    queued_count := queued_count + 1;
  end loop;
  return queued_count;
end;
$$;

revoke all on function private.enqueue_due_automation_schedules() from public, anon, authenticated, service_role;

create or replace function private.process_background_jobs(p_limit integer default 50)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  target public.background_jobs%rowtype;
  processed_count integer := 0;
  notification_title text;
  notification_body text;
  notification_href text;
  notification_category text;
begin
  for target in
    select *
    from public.background_jobs
    where (
      (status = 'queued' and run_at <= now())
      or (status = 'running' and locked_at < now() - interval '10 minutes')
    )
    order by priority, run_at, id
    limit least(greatest(p_limit, 1), 100)
    for update skip locked
  loop
    begin
      update public.background_jobs
      set status = 'running', locked_at = now(), locked_by = 'supabase-cron',
          attempts = attempts + 1, last_error = null
      where id = target.id;

      update public.automation_runs
      set status = 'running', started_at = coalesce(started_at, now()), error_message = null
      where id = target.run_id;

      notification_title := coalesce(nullif(trim(target.payload ->> 'title'), ''), 'Automation completed');
      notification_body := nullif(trim(target.payload ->> 'body'), '');
      notification_href := nullif(trim(target.payload ->> 'href'), '');
      notification_category := case
        when target.payload ->> 'category' in ('System','Delivery','Operations','Commercial','Finance','Support','Documents','Import')
          then target.payload ->> 'category'
        else 'System'
      end;
      if notification_href is not null and (notification_href not like '/%' or notification_href like '//%') then
        notification_href := null;
      end if;

      insert into public.notifications(organization_id, user_id, title, body, category, href)
      select target.organization_id, m.user_id, notification_title, notification_body, notification_category, notification_href
      from public.memberships m
      where m.organization_id = target.organization_id and m.status = 'active';

      update public.background_jobs
      set status = 'succeeded', locked_at = null, locked_by = null
      where id = target.id;
      update public.automation_runs
      set status = 'succeeded', output = jsonb_build_object('notified', true), completed_at = now()
      where id = target.run_id;
      update public.automation_rules
      set run_count = run_count + 1, last_run_at = now()
      where id = target.rule_id;
      processed_count := processed_count + 1;
    exception when others then
      update public.background_jobs
      set status = case when attempts >= max_attempts then 'dead' else 'queued' end,
          run_at = now() + make_interval(mins => least(60, greatest(1, attempts * attempts))),
          locked_at = null, locked_by = null, last_error = left(sqlerrm, 2000)
      where id = target.id;
      update public.automation_runs
      set status = case
            when (select attempts >= max_attempts from public.background_jobs where id = target.id) then 'failed'
            else 'queued'
          end,
          error_message = left(sqlerrm, 2000),
          completed_at = case
            when (select attempts >= max_attempts from public.background_jobs where id = target.id) then now()
            else null
          end
      where id = target.run_id;
    end;
  end loop;
  return processed_count;
end;
$$;

revoke all on function private.process_background_jobs(integer) from public, anon, authenticated, service_role;

-- Schedule both stages independently. Direct cron.job writes are intentionally
-- avoided; current Supabase only supports the cron management functions.
create extension if not exists pg_cron;
do $$
begin
  if not exists (select 1 from cron.job where jobname = 'unison-enqueue-automations') then
    perform cron.schedule(
      'unison-enqueue-automations', '* * * * *',
      'select private.enqueue_due_automation_schedules();'
    );
  end if;
  if not exists (select 1 from cron.job where jobname = 'unison-process-automation-jobs') then
    perform cron.schedule(
      'unison-process-automation-jobs', '* * * * *',
      'select private.process_background_jobs(50);'
    );
  end if;
end;
$$;

