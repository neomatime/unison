create or replace function public.is_himark_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.memberships m
    join public.organizations o on o.id = m.organization_id
    where m.user_id = (select auth.uid())
      and m.status = 'active'
      and m.role_id in ('owner', 'admin')
      and o.slug = 'himark'
      and o.status = 'active'
  );
$$;

revoke all on function public.is_himark_admin() from public, anon;
grant execute on function public.is_himark_admin() to authenticated, service_role;

